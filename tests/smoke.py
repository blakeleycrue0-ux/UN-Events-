from pin_helpers import unlock_app, confirm_action
"""Run against the local server: python3 tests/smoke.py. Requires Playwright + Chromium.
Uses Chromium's synthetic camera. Does not validate iPhone hardware or real detection accuracy.
"""
from playwright.sync_api import sync_playwright
import os
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=os.environ.get('CHROMIUM','/usr/bin/chromium'),headless=True,args=['--no-sandbox','--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream'])
    context=browser.new_context(permissions=['camera'],accept_downloads=True)
    page=context.new_page();page.add_init_script("document.addEventListener('DOMContentLoaded',()=>document.querySelectorAll('details').forEach(d=>d.open=true))")
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('console',lambda m:print('BROWSER',m.type,m.text[:300]) if m.type=='error' else None)
    page.goto('http://127.0.0.1:8001/camara.html#camera');unlock_app(page)
    page.wait_for_function('!!db')
    page.click('#camera')
    page.wait_for_function('!!state.stream && video.videoWidth>0')
    assert page.evaluate('state.stream.getAudioTracks().length')==0
    page.wait_for_function("document.getElementById('live').textContent==='LIVE'")
    print('PASS camera: live and no microphone')
    page.select_option('#clip','10')
    page.click('#record')
    page.wait_for_function('state.recording')
    assert page.locator('#rec').is_visible()
    page.wait_for_function('!state.recording',timeout=20000)
    page.wait_for_selector('.clip video')
    assert page.evaluate("events.some(e=>e.type==='grabación'&&e.message.includes('guardada'))")
    v=page.locator('.clip video').first
    v.evaluate('(v)=>v.load()')
    page.wait_for_function("document.querySelector('.clip video').readyState>=1")
    assert v.evaluate('(v)=>v.duration')>0
    page.get_by_text('Marcar importante',exact=True).first.click()
    page.wait_for_selector('button:text("Importante ✓")')
    print('PASS recording: real MediaRecorder clip saved, playable, marked important')
    page.click('#testSpeaker')
    page.click('#alarm');confirm_action(page)
    page.wait_for_function('state.alarm && !!siren')
    page.click('#silence')
    page.wait_for_function('!state.alarm && !siren')
    print('PASS siren start/stop')
    page.evaluate("""async()=>{window.fixture=document.createElement('canvas');fixture.width=640;fixture.height=480;const c=fixture.getContext('2d');let n=0;window.fixtureTimer=setInterval(()=>{c.fillStyle='#777';c.fillRect(0,0,640,480);c.fillStyle='#fff';c.fillRect((n++%2)*300,100,220,260)},500);video.srcObject=fixture.captureStream(10);await video.play();}""")
    page.click('#protect');confirm_action(page)
    page.wait_for_function('state.armed')
    page.wait_for_function("events.some(e=>e.type==='movimiento')",timeout=20000)
    assert not page.evaluate('state.alarm')
    print('PASS motion on controlled moving canvas fixture; no default auto alarm')
    page.click('#zone');confirm_action(page)
    page.locator('#overlay').scroll_into_view_if_needed()
    box=page.locator('#overlay').bounding_box()
    page.mouse.move(box['x']+box['width']*.3,box['y']+box['height']*.3)
    page.mouse.down();page.mouse.move(box['x']+box['width']*.7,box['y']+box['height']*.7);page.mouse.up()
    page.wait_for_function('!!state.zone && state.zone.w<.9')
    print('PASS zone drawing')
    page.locator('#person').evaluate("e=>{e.checked=true;e.dispatchEvent(new Event('change'))}")
    page.wait_for_function('!!state.model || !document.getElementById("person").checked',timeout=90000)
    assert page.evaluate('!!state.model'),page.locator('#error').inner_text()
    page.wait_for_function('lastAI>0 && !state.busy',timeout=90000)
    print('PASS local AI load and inference')
    page.locator('#diagnose').evaluate('e=>e.click()')
    page.wait_for_function("document.getElementById('diagnostics').textContent.includes('correcta')")
    page.click('#camera');confirm_action(page)
    page.wait_for_function('!state.stream')
    assert not page.evaluate('state.recording || state.alarm')
    assert not errors,errors
    print('PASS shutdown, IndexedDB roundtrip, no uncaught JS exceptions')
    browser.close()
